#!/usr/bin/env bash

# 1. Calculate Uptime
uptime_raw=$(uptime -p)
days=$(echo "$uptime_raw" | grep -oE '[0-9]+ day' | grep -oE '[0-9]+')
hours=$(echo "$uptime_raw" | grep -oE '[0-9]+ hour' | grep -oE '[0-9]+')

uptime_str=""
if [[ -n "$days" ]]; then
    uptime_str="${days}d "
fi
if [[ -n "$hours" ]]; then
    uptime_str="${uptime_str}${hours}h"
else
    uptime_str="${uptime_str}0h"
fi
if [[ -z "$uptime_str" || "$uptime_str" == "0h" ]]; then
    mins=$(echo "$uptime_raw" | grep -oE '[0-9]+ minute' | grep -oE '[0-9]+')
    uptime_str="${mins}m"
fi

# 2. Local active Git project
local_repo=$(find /home/priyam/Projects -maxdepth 3 -name ".git" -type d -exec stat -c "%Y %n" {} + 2>/dev/null | sort -nr | head -n 1 | cut -d' ' -f2-)
project_name=""
branch=""
commits_today=""

if [[ -n "$local_repo" ]]; then
    repo_dir=$(dirname "$local_repo")
    project_name=$(basename "$repo_dir")
    branch=$(cd "$repo_dir" && git branch --show-current 2>/dev/null)
    commits_count=$(cd "$repo_dir" && git log --since="00:00:00" --oneline 2>/dev/null | wc -l)
    if [[ "$commits_count" -eq 1 ]]; then
        commits_today="1 commit today"
    else
        commits_today="${commits_count} commits today"
    fi
fi

# Fallback if no local git repo was found
if [[ -z "$project_name" ]]; then
    CACHE_REPOS="$HOME/.cache/quickshell/github_repos.json"
    if [[ -f "$CACHE_REPOS" ]]; then
        project_name=$(jq -r '.[0].name' "$CACHE_REPOS" 2>/dev/null)
        branch="main"
        commits_today="0 commits today"
    fi
fi

if [[ -z "$project_name" ]]; then
    project_name="No Active Project"
    branch="main"
    commits_today="0 commits today"
fi

# 3. Read Next Reminder
REMINDERS_FILE="$HOME/.config/rofi/reminders.txt"
reminder_title="No Reminders"
reminder_time="All caught up!"

if [[ -f "$REMINDERS_FILE" ]]; then
    first_line=$(head -n 1 "$REMINDERS_FILE")
    if [[ -n "$first_line" ]]; then
        # Parse using pipe separator
        title="${first_line%%|*}"
        time="${first_line#*|}"
        reminder_title=$(echo "$title" | xargs)
        reminder_time=$(echo "$time" | xargs)
    fi
fi

# 4. Write to dynamic_widgets.rasi
cat <<EOF > "$HOME/.config/rofi/dynamic_widgets.rasi"
/* Dynamic variables generated by dynamic_widgets.sh */
* {
    uptime-value: "${uptime_str}";
    github-project: "${project_name}";
    github-branch: "${branch}";
    github-commits: "${commits_today}";
    reminder-title: "${reminder_title}";
    reminder-time: "${reminder_time}";
}
EOF
