#!/usr/bin/env bash

PDF_DIR="$HOME/Documents/PDFs"
THUMB_DIR="$PDF_DIR/.thumbs"

mkdir -p "$THUMB_DIR"

if [[ "$1" == "--update" ]]; then
    # Generate thumbnails for all PDFs in the directory
    find "$PDF_DIR" -maxdepth 1 -name "*.pdf" | while read -r pdf; do
        [[ -f "$pdf" ]] || continue
        filename=$(basename "$pdf")
        thumb_name="${filename%.pdf}.png"
        thumb_path="$THUMB_DIR/$thumb_name"
        
        # Check if thumbnail doesn't exist or is older than the PDF
        if [[ ! -f "$thumb_path" || "$pdf" -nt "$thumb_path" ]]; then
            # Generate thumbnail of the first page (scale width to 400px)
            pdftoppm -png -f 1 -l 1 -scale-to-x 400 -scale-to-y -1 "$pdf" "${thumb_path%.png}"
            # Find the file generated by pdftoppm (e.g. prefix-1.png or prefix-01.png)
            generated_file=$(find "$THUMB_DIR" -maxdepth 1 -name "$(basename "${thumb_path%.png}")-*.png" | head -n 1)
            if [[ -n "$generated_file" && -f "$generated_file" ]]; then
                mv "$generated_file" "$thumb_path"
            fi
        fi
    done
    exit 0
elif [[ "$1" == "--open" && -n "$2" ]]; then
    xdg-open "$2" &
    exit 0
fi
